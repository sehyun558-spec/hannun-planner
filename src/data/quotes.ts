/** 글자로 정해진 번호 만들기 (같은 글자면 항상 같은 번호) */
function hash(s: string): number {
  let h = 5381
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0
  return h
}

/**
 * 보여줄 순서: 위인의 말과 응원 문구가 골고루 섞이도록, 문장마다 정해진 번호 순으로 늘어놓아요.
 * (목록에 문장을 추가하면 순서가 한 번 새로 정해져요)
 */
const ORDER: Quote[] = [...QUOTES].sort((a, b) => hash(a.text) - hash(b.text) || a.text.localeCompare(b.text))

/** 'YYYY-MM-DD' → 날짜 번호 (하루에 1씩 커져요) */
function dayNumber(date: string): number {
  const [y, m, d] = date.split('-').map(Number)
  return Math.floor(Date.UTC(y, m - 1, d) / 86_400_000)
}

/**
 * 오늘의 한 줄: 날짜로만 정해져서 같은 날에는 언제 열어도 같은 문장.
 * 하루에 한 칸씩 차례대로 넘어가서, 목록을 한 바퀴 다 돌기 전에는 같은 문장이 다시 나오지 않아요.
 */
export function quoteOfDay(date: string): Quote {
  return ORDER[dayNumber(date) % ORDER.length]
}
