export const QUOTES: Record<DayPart, Quote[]> = {
  morning: MORNING,
  day: DAY,
  evening: EVENING,
}

/** 글자로 정해진 번호 만들기 (같은 글자면 항상 같은 번호) */
function hash(s: string): number {
  let h = 5381
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0
  return h
}

/** 오늘의 한 줄: 같은 날, 같은 시간대에는 몇 번을 열어도 같은 문장 */
export function quoteOfDay(date: string, part: DayPart): Quote {
  const list = QUOTES[part]
  return list[hash(`${date}|${part}`) % list.length]
}

/** 완료 축하용 짧은 한 줄 (같은 날 같은 시간대면 같은 문장, 오늘의 한 줄과는 되도록 다르게) */
export function cheerQuote(date: string, part: DayPart): Quote {
  const main = quoteOfDay(date, part)
  const short = QUOTES[part].filter((q) => q.text.length <= 24 && q !== main)
  return short[hash(`${date}|${part}|cheer`) % short.length]
}
